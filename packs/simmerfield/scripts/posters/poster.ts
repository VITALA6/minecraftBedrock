// wm_kitchen:recipe_poster (D15): a 2×1 wall poster showing one recipe; sneak + use cycles through the
// How to Start guide and the recipes the using player has discovered, plain use names the dish
// and its effect. A player's first poster shows the guide (wm_kitchen:guide_placed).
//
// The two blocks are one minecraft:multi_block (2 parts, horizontal, stable at block format
// 1.26.50): the game places both parts together and breaks them together. The multi-block trait
// allows no other trait except placement_direction (cardinal_direction), so the facing comes from
// the clicked face here, in beforeOnPlayerPlace, as the custom state wm_kitchen:facing. The parts go along
// the stored cardinal direction (y_rotation_offset 90 turns it along the wall); which part ends up
// on the viewer's right isn't something this code assumes: a tick after placing, it reads where
// the parts really are (Block.getParts); each part's half comes from its part number. The block JSON is generated by
// tools/gen-poster-block.mjs: one permutation per wm_kitchen:facing × half × wm_kitchen:poster.
//
// Drops: both parts' loot tables are empty and the script drops one poster per break (onBreak or
// onPlayerBreak, deduplicated), so a 2-part break can't drop two or none. Creative breaks drop
// nothing.

const useGate = new TickGate(POSTER_USE_GAP_TICKS);

function discoveryOf(player: Player): Discovery {
  return { found: foundCrops(player), creative: isCreative(player) };
}

/** The poster's parts (both when loaded), or just this block if the game can't say. */
function partsOf(block: Block): Block[] {
  try {
    const parts = block.getParts();
    if (parts && parts.length > 0) return parts;
  } catch {
    // unloaded neighbour chunk
  }
  return [block];
}

function facingOf(block: Block): Facing | undefined {
  const value = getState(block, STATE_FACING);
  return isFacing(value) ? value : undefined;
}

const isSolid = (block: Block | undefined) =>
  block !== undefined && !block.isAir && !block.isLiquid;

/** The poster index a part shows (wm_kitchen:poster within wm_kitchen:poster_page). */
function indexOf(block: Block): number {
  const slot = getNumberState(block, STATE_POSTER) ?? POSTER_GUIDE;
  return posterIndexOf(slot, getNumberState(block, STATE_POSTER_PAGE) ?? 0);
}

/** The state patch that makes a part show poster `index`. */
function indexPatch(index: number): Record<string, StateValue> {
  const { slot, page } = posterStates(index);
  return { [STATE_POSTER]: slot, [STATE_POSTER_PAGE]: page };
}

const center = ({ x, y, z }: Vector3): Vector3 => ({ x: x + 0.5, y: y + 0.5, z: z + 0.5 });

// --- what a poster says --------------------------------------------------------------------------

function showInfo(player: Player, index: number): void {
  const dishId = posterDish(index);
  const dish = dishId ? findDish(dishId) : undefined;
  if (!dishId || !dish) return actionBar(player, t("wm_kitchen.poster.guide"));
  const effect = dish.effect;
  const info = effect && EFFECTS[effect.effect];
  const family = familyOf(dish);
  actionBar(
    player,
    effect && info && family
      ? t("wm_kitchen.poster.dish", itemName(dishId), family.glyph, { translate: info.nameKey }, effect.seconds) // prettier-ignore
      : t("wm_kitchen.poster.dish_plain", itemName(dishId)),
  );
}

function cycle(player: Player, block: Block): void {
  const next = nextPoster(indexOf(block), discoveryOf(player));
  if (next === undefined) {
    sound(block.dimension, SOUND.tap, center(block.location));
    return actionBar(player, t("wm_kitchen.poster.none"));
  }
  for (const part of partsOf(block)) setStates(part, indexPatch(next));
  sound(block.dimension, SOUND.pageTurn, center(block.location));
  showInfo(player, next);
}

// --- placing -------------------------------------------------------------------------------------

/** Removes a poster that can't hang (no wall, parts not along the wall) and gives it back. */
function refund(parts: readonly Block[], player: Player | undefined, reason: string): void {
  // The Content Log is how a refused poster gets diagnosed (in game the poster just vanishes).
  console.warn(
    `[simmerfield] recipe poster removed (${reason}) at ` +
      parts.map((part) => JSON.stringify(part.location)).join(" + "),
  );
  for (const part of parts) {
    try {
      // the item comes back below; if removing a part counts as a break, it must not drop too
      dropOnce(part.dimension, part.location, false);
      if (part.typeId === BLOCK_RECIPE_POSTER) part.setType("minecraft:air");
    } catch {
      // already gone
    }
  }
  if (!player?.isValid) return;
  if (!isCreative(player)) {
    giveOrDrop(player, ITEM_RECIPE_POSTER, 1, player.dimension, player.location);
  }
  actionBar(player, t(reason));
}

/**
 * A tick after placing: give every part the same facing and recipe, and the half it shows from
 * where it really is. Retries once later if the second part isn't there yet (the game delays a
 * part that lands in a chunk that isn't fully loaded).
 */
function settle(dimension: Dimension, location: Vector3, player: Player | undefined, retry = true) {
  const block = dimension.getBlock(location);
  if (block?.typeId !== BLOCK_RECIPE_POSTER) return; // the game didn't place it
  const hint = facingOf(block);
  const parts = partsOf(block);
  if (parts.length < 2) {
    if (retry) {
      system.runTimeout(() => settle(dimension, location, player, false), POSTER_SYNC_RETRY_TICKS);
    } else {
      console.warn(
        `[simmerfield] recipe poster at ${JSON.stringify(location)}: second part never appeared`,
      );
    }
    return;
  }
  const [a, b] = parts as [Block, Block];
  // The facing comes from the world (where the wall really is), not only from the clicked face:
  // reading `face` the wrong way round refused every poster on 2026-10-22 ("no_room").
  const facing = settleFacing([a.location, b.location], hint, (at) => {
    try {
      return isSolid(dimension.getBlock(at));
    } catch {
      return false;
    }
  });
  if (!facing) return refund(parts, player, "wm_kitchen.poster.no_room");
  if (!halvesOf(facing, a.location, b.location)) {
    console.warn(
      `[simmerfield] recipe poster parts at ${JSON.stringify(a.location)} and ` +
        `${JSON.stringify(b.location)} aren't side by side facing ${facing}: check ` +
        `y_rotation_offset in tools/gen-poster-block.mjs`,
    );
    return refund(parts, player, "wm_kitchen.poster.look");
  }
  // Normally nothing to write: facing and recipe came with the placement, the half from the
  // part number. Only a facing the world disagrees with is fixed, on every part.
  if (facing !== hint) for (const part of parts) setStates(part, { [STATE_FACING]: facing });
}

// --- breaking ------------------------------------------------------------------------------------

/** "dimension:x,y,z" -> tick of a drop there (or next to it), so one break drops one poster. */
const dropped = new Map<string, number>();
const keyOf = (dimension: Dimension, { x, y, z }: Vector3) => `${dimension.id}:${x},${y},${z}`;

function dropOnce(dimension: Dimension, location: Vector3, drop: boolean): void {
  const now = system.currentTick;
  const last = dropped.get(keyOf(dimension, location));
  if (last !== undefined && now - last <= 2) return;
  // Mark the part and its neighbours: the other part's event (if the game sends one) is next to it.
  for (const [dx, dz] of [
    [0, 0],
    [1, 0],
    [-1, 0],
    [0, 1],
    [0, -1],
  ] as const) {
    dropped.set(keyOf(dimension, { x: location.x + dx, y: location.y, z: location.z + dz }), now);
  }
  if (dropped.size > 256) {
    for (const [key, tick] of dropped) if (now - tick > 2) dropped.delete(key);
  }
  if (!drop) return;
  const at = center(location);
  system.run(() => {
    try {
      dimension.spawnItem(new ItemStack(ITEM_RECIPE_POSTER), at);
    } catch (error) {
      console.warn(`[simmerfield] poster drop failed: ${String(error)}`);
    }
  });
}

const recipePoster: BlockCustomComponent = {
  beforeOnPlayerPlace(event) {
    const { block, face, player } = event;
    // `face` is the clicked face of the wall block, i.e. the poster's front (seen in game
    // 2026-10-22: face East, wall at x-1). settle() re-checks it against the world.
    const facing = facingOfDirection(face);
    const cardinal = event.permutationToPlace.getAllStates()[STATE_CARDINAL];
    const half = facing && isFacing(cardinal) ? startHalf(facing, cardinal) : undefined;
    if (!facing || !half) {
      // up/down faces are refused by the placement filter; this is the player looking along
      // the wall, so the second part would go into it or stick out of it.
      event.cancel = true;
      if (player) system.run(() => actionBar(player, t("wm_kitchen.poster.look")));
      return;
    }
    // Both parts get these from the placement; the half each shows comes from its part number.
    const guidePlaced = player?.getDynamicProperty(PLAYER_GUIDE_PLACED) === true;
    const patch: Record<string, StateValue> = {
      [STATE_FACING]: facing,
      ...indexPatch(player ? firstPoster(discoveryOf(player), guidePlaced) : POSTER_GUIDE),
    };
    event.permutationToPlace = BlockPermutation.resolve(BLOCK_RECIPE_POSTER, {
      ...event.permutationToPlace.getAllStates(),
      ...patch,
    });
    const { dimension, location } = block;
    // Before-events run in restricted mode: fix up the parts next tick (and only then count the
    // guide as placed: a poster the game didn't place leaves it for the next one).
    system.run(() => {
      settle(dimension, location, player);
      if (
        player?.isValid &&
        !guidePlaced &&
        dimension.getBlock(location)?.typeId === BLOCK_RECIPE_POSTER
      ) {
        player.setDynamicProperty(PLAYER_GUIDE_PLACED, true);
      }
    });
  },

  onPlayerInteract({ block, player }) {
    // Sneak + use is handled in the before-event (registerPosterEvents), which cancels it.
    if (!player || player.isSneaking) return;
    if (!useGate.pass(player.id, system.currentTick)) return;
    showInfo(player, indexOf(block));
  },

  onPlayerBreak({ block, dimension, player }) {
    dropOnce(dimension, block.location, !(player && isCreative(player)));
  },

  onBreak({ block, dimension, entitySource }) {
    const creative = entitySource instanceof Player && isCreative(entitySource);
    dropOnce(dimension, block.location, !creative);
  },
};

export function registerRecipePoster(registry: BlockComponentRegistry): void {
  registry.registerCustomComponent(COMPONENT_RECIPE_POSTER, recipePoster);
}

/**
 * Sneak + use goes through the before-event (as on the pot): whether onPlayerInteract fires while
 * sneaking with an item isn't proven, and holding a block would place it against the poster.
 * The event is cancelled and the poster cycles next tick; the component skips sneaking players.
 */
export function registerPosterEvents(): void {
  world.beforeEvents.playerInteractWithBlock.subscribe((event) => {
    const { block, player, isFirstEvent } = event;
    if (block.typeId !== BLOCK_RECIPE_POSTER || !player.isSneaking) return;
    event.cancel = true;
    if (!isFirstEvent) return;
    const { dimension, location } = block;
    system.run(() => {
      if (!player.isValid || !useGate.pass(player.id, system.currentTick)) return;
      const now = dimension.getBlock(location);
      if (now?.typeId === BLOCK_RECIPE_POSTER) cycle(player, now);
    });
  });
}
